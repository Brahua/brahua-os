// Generates src/design-system/styles/tailwind-theme.css from the Claude Design token files.
// Tailwind only needs the token *names* to emit utilities; the actual values (and their light/dark
// switch) come from the unlayered token files, which override the @theme layer.
import { readFileSync, writeFileSync } from "node:fs";

const dir = "src/design-system/styles/tokens";
const read = (f) => readFileSync(`${dir}/${f}`, "utf8");

/** First block of `--name: value;` declarations after the given selector. */
function decls(css, selectorPattern) {
  const block = css.match(new RegExp(`${selectorPattern}\\s*\\{([^}]*)\\}`))[1];
  return [...block.matchAll(/--([\w-]+):\s*([^;]+);/g)].map(([, name, value]) => [
    name,
    value.trim(),
  ]);
}

const colors = decls(read("colors.css"), String.raw`:root,\s*\[data-theme="dark"\]`);
const shadows = decls(read("shadows.css"), String.raw`:root,\s*\[data-theme="dark"\]`);
const spacing = decls(read("spacing.css"), ":root");
const typography = decls(read("typography.css"), ":root");
const motion = decls(read("motion.css"), ":root");

const lines = [
  "/* GENERATED by scripts/build-tailwind-theme.mjs from the Claude Design tokens — do not edit. */",
  '@custom-variant light (&:where([data-theme="light"], [data-theme="light"] *));',
  '@custom-variant dark (&:where(:root:not([data-theme="light"]), [data-theme="dark"], [data-theme="dark"] *));',
  "",
  "@theme {",
  "  --color-*: initial;",
  "  --spacing: 4px;",
];
for (const [name, value] of colors) {
  if (name.startsWith("color-")) lines.push(`  --${name}: ${value};`);
  // Area colors become Tailwind colors that follow the theme: bg-area-home, text-area-home-inverse…
  if (name.startsWith("area-")) lines.push(`  --color-${name}: var(--${name});`);
}
for (const [name, value] of shadows) lines.push(`  --${name}: ${value};`);
for (const [name, value] of spacing)
  if (name.startsWith("radius-")) lines.push(`  --${name}: ${value};`);
for (const [name, value] of typography) {
  if (
    name.startsWith("font-") ||
    (name.startsWith("text-") &&
      !name.endsWith("--font-family") &&
      !name.endsWith("--font-stretch"))
  )
    lines.push(`  --${name}: ${value};`);
}
for (const [name, value] of motion)
  if (name.startsWith("ease-")) lines.push(`  --${name}: ${value};`);
lines.push("  --breakpoint-2xl: 1440px;", "}", "");

writeFileSync("src/design-system/styles/tailwind-theme.css", lines.join("\n"));
console.log(`tailwind-theme.css: ${lines.length} lines`);
